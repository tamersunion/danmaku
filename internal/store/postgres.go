func (p *Postgres) Get(ctx context.Context, id string) (*domain.Danmaku, error) {
	if !validUUID(id) {
		item := domain.Danmaku{ID: "00000000-0000-0000-0000-000000000000", Data: domain.NewDanmakuData(), CreateTime: time.Now().UTC(), UpdateTime: time.Now().UTC()}
		return &item, nil
	}
	item, err := scanDanmaku(p.pool.QueryRow(ctx, `SELECT "Id"::text,"Vid","Data",COALESCE("Ip"::text,''),"IsDelete","CreateTime","UpdateTime" FROM "Danmu" WHERE "Id"=$1`, id))
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var video domain.Video
	var raw []byte
	err = p.pool.QueryRow(ctx, `SELECT v."Id",v."Vid",v."Referer",v."CreateTime",v."UpDateTime" FROM "Video" v JOIN "Danmu" d ON d."VideoId"=v."Id" WHERE d."Id"=$1`, id).Scan(&video.ID, &video.Vid, &raw, &video.CreateTime, &video.UpdateTime)
	if err == nil {
		if decodeErr := json.Unmarshal(raw, &video.Referer); decodeErr != nil {
			return nil, decodeErr
		}
		item.Video = &video
	} else if !errors.Is(err, pgx.ErrNoRows) {
		return nil, err
	}
	return &item, nil
}

func (p *Postgres) Edit(ctx context.Context, id string, changes domain.DanmakuData, isDeleted bool) (*domain.Danmaku, error) {
	if !validUUID(id) {
		return nil, nil
	}
	current, err := p.Get(ctx, id)
	if err != nil || current == nil {
		return current, err
	}
	current.Data.Time = changes.Time
	current.Data.Mode = changes.Mode
	current.Data.Color = changes.Color
	if changes.Text != nil {
		current.Data.Text = changes.Text
	}
	raw, err := domain.MarshalDBData(current.Data)
	if err != nil {
		return nil, err
	}
	current.IsDeleted = isDeleted
	current.UpdateTime = time.Now().UTC().Truncate(time.Second)
	command, err := p.pool.Exec(ctx, `UPDATE "Danmu" SET "Data"=$2,"IsDelete"=$3,"UpdateTime"=$4 WHERE "Id"=$1`, id, raw, current.IsDeleted, current.UpdateTime)
	if err != nil || command.RowsAffected() == 0 {
		return nil, err
	}
	current.Video = nil
	return current, nil
}

func (p *Postgres) Delete(ctx context.Context, id string) (bool, error) {
	if !validUUID(id) {
		return false, nil
	}
	command, err := p.pool.Exec(ctx, `UPDATE "Danmu" SET "IsDelete"=TRUE,"UpdateTime"=$2 WHERE "Id"=$1`, id, time.Now().UTC().Truncate(time.Second))
	return err == nil && command.RowsAffected() > 0, err
}

func (p *Postgres) VerifyPassword(ctx context.Context, name, password string) (bool, int, int, error) {
	var uid, role int
	var stored, salt string
	err := p.pool.QueryRow(ctx, `SELECT "Id","Role","PassWord","Salt" FROM "User" WHERE "Name"=$1 LIMIT 1`, name).Scan(&uid, &role, &stored, &salt)
	if errors.Is(err, pgx.ErrNoRows) {
		return false, 0, 3, nil
	}
	if err != nil {
		return false, 0, 3, err
	}
	if stored == saltedMD5(password, salt) {
		return true, uid, role, nil
	}
	if p.admin.User == name && strings.EqualFold(password, md5String(p.admin.Password)) {
		return true, 0, 1, nil
	}
	return false, 0, 3, nil
}

func (p *Postgres) ChangePassword(ctx context.Context, id int, oldPassword, newPassword string) (bool, error) {
	if strings.TrimSpace(oldPassword) == "" || strings.TrimSpace(newPassword) == "" {
		return false, nil
	}
	var stored, salt string
	err := p.pool.QueryRow(ctx, `SELECT "PassWord","Salt" FROM "User" WHERE "Id"=$1`, id).Scan(&stored, &salt)
	if errors.Is(err, pgx.ErrNoRows) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if stored != saltedMD5(oldPassword, salt) {
		return false, nil
	}
	newSalt, err := randomString(6)
	if err != nil {
		return false, err
	}
	command, err := p.pool.Exec(ctx, `UPDATE "User" SET "PassWord"=$2,"Salt"=$3,"UpdateTime"=$4 WHERE "Id"=$1`, id, saltedMD5(newPassword, newSalt), newSalt, time.Now().UTC().Truncate(time.Millisecond))
	return err == nil && command.RowsAffected() > 0, err
}

func (p *Postgres) ChangeUserInfo(ctx context.Context, id int, name string, email, phone *string) (bool, error) {
	var count int
	if err := p.pool.QueryRow(ctx, `SELECT COUNT(*) FROM "User" WHERE "Name"=$1 AND "Id"<>$2`, name, id).Scan(&count); err != nil {
		return false, err
	}
	if count > 0 {
		return false, nil
	}
	command, err := p.pool.Exec(ctx, `UPDATE "User" SET "Name"=COALESCE(NULLIF($2,''),"Name"),"Email"=COALESCE($3,"Email"),"PhoneNumber"=COALESCE($4,"PhoneNumber"),"UpdateTime"=$5 WHERE "Id"=$1`, id, name, email, phone, time.Now().UTC().Truncate(time.Millisecond))
	return err == nil && command.RowsAffected() > 0, err
}

func (p *Postgres) User(ctx context.Context, id int) (*domain.User, error) {
	var user domain.User
	err := p.pool.QueryRow(ctx, `SELECT "Id","Name","Role","PhoneNumber","Email","CreateTime","UpdateTime" FROM "User" WHERE "Id"=$1`, id).Scan(&user.ID, &user.Name, &user.Role, &user.PhoneNumber, &user.Email, &user.CreateTime, &user.UpdateTime)
	if errors.Is(err, pgx.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	user.Salt, _ = randomString(6)
	return &user, nil
}

func (p *Postgres) Cache(ctx context.Context, key string, lifetime time.Duration, fetch func(context.Context) ([]byte, error)) ([]byte, error) {
	var id int
	var value []byte
	var timestamp int64
	err := p.pool.QueryRow(ctx, `SELECT "Id","Value","TimeStamp" FROM "HttpClientCache" WHERE "Key"=$1 LIMIT 1`, key).Scan(&id, &value, &timestamp)
	if err == nil && len(value) > 0 && time.Now().Unix()-timestamp <= int64(lifetime.Seconds()) {
		return value, nil
	}
	if err != nil && !errors.Is(err, pgx.ErrNoRows) {
		return nil, err
	}
	value, err = fetch(ctx)
	if err != nil {
		return nil, err
	}
	now := time.Now().Unix()
	if id != 0 {
		_, err = p.pool.Exec(ctx, `UPDATE "HttpClientCache" SET "Value"=$2,"TimeStamp"=$3 WHERE "Id"=$1`, id, value, now)
	} else {
		_, err = p.pool.Exec(ctx, `INSERT INTO "HttpClientCache" ("Key","Value","TimeStamp") VALUES ($1,$2,$3)`, key, value, now)
	}
	return value, err
}

func normalizePage(page, size int) (int, int) {
	if page < 1 {
		page = 1
	}
	if size < 1 {
		size = 30
	}
	return page, size
}

func md5String(value string) string {
	sum := md5.Sum([]byte(value))
	return hex.EncodeToString(sum[:])
}

func saltedMD5(value, salt string) string {
	if salt == "" {
		return md5String(value)
	}
	if len(value) >= 2 {
		value = value[2:]
	}
	return md5String(value + salt)
}

func randomString(length int) (string, error) {
	const alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
	buffer := make([]byte, length)
	raw := make([]byte, length)
	if _, err := rand.Read(raw); err != nil {
		return "", err
	}
	for index := range raw {
		buffer[index] = alphabet[int(raw[index])%len(alphabet)]
	}
	return string(buffer), nil
}

func randomUUID() (string, error) {
	value := make([]byte, 16)
	if _, err := rand.Read(value); err != nil {
		return "", err
	}
	value[6] = (value[6] & 0x0f) | 0x40
	value[8] = (value[8] & 0x3f) | 0x80
	return fmt.Sprintf("%08x-%04x-%04x-%04x-%012x", value[0:4], value[4:6], value[6:8], value[8:10], value[10:16]), nil
}

func validUUID(value string) bool {
	if len(value) != 36 {
		return false
	}
	for index, char := range value {
		if index == 8 || index == 13 || index == 18 || index == 23 {
			if char != '-' {
				return false
			}
			continue
		}
		if !strings.ContainsRune("0123456789abcdefABCDEF", char) {
			return false
		}
	}
	return true
}

func ParseReferer(raw string) (domain.Referer, error) {
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Scheme == "" || parsed.Hostname() == "" {
		return domain.Referer{}, errors.New("invalid referer URL")
	}
	port := 0
	if parsed.Port() != "" {
		_, _ = fmt.Sscanf(parsed.Port(), "%d", &port)
	} else if parsed.Scheme == "https" {
		port = 443
	} else if parsed.Scheme == "http" {
		port = 80
	}
	path := parsed.EscapedPath()
	if path == "" {
		path = "/"
	}
	return domain.Referer{Protocol: parsed.Scheme, Host: parsed.Hostname(), Port: port, Path: path, Query: queryWithPrefix(parsed.RawQuery), Fragment: fragmentWithPrefix(parsed.Fragment)}, nil
}

func queryWithPrefix(value string) string {
	if value == "" {
		return ""
	}
	return "?" + value
}

func fragmentWithPrefix(value string) string {
	if value == "" {
		return ""
	}
	return "#" + value
}
