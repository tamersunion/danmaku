type Postgres struct {
	pool  *pgxpool.Pool
	admin config.AdminSettings
}

func Open(ctx context.Context, cfg config.Config) (*Postgres, error) {
	poolConfig, err := pgxpool.ParseConfig(cfg.DanmakuSQL.ConnectionString())
	if err != nil {
		return nil, fmt.Errorf("parse PostgreSQL configuration: %w", err)
	}
	poolConfig.MaxConns = cfg.DanmakuSQL.PoolSize
	pool, err := pgxpool.NewWithConfig(ctx, poolConfig)
	if err != nil {
		return nil, fmt.Errorf("open PostgreSQL pool: %w", err)
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("connect to PostgreSQL: %w", err)
	}
	return &Postgres{pool: pool, admin: cfg.Admin}, nil
}

func (p *Postgres) Close() { p.pool.Close() }

func (p *Postgres) Initialize(ctx context.Context) error {
	statements := []string{
		`CREATE TABLE IF NOT EXISTS "User" (
			"Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			"Name" character varying(16) NOT NULL,
			"PassWord" text NOT NULL,
			"Salt" text NOT NULL,
			"Role" integer NOT NULL,
			"PhoneNumber" text NULL,
			"Email" text NULL,
			"CreateTime" timestamp(3) without time zone NOT NULL,
			"UpdateTime" timestamp(3) without time zone NOT NULL
		)`,
		`CREATE TABLE IF NOT EXISTS "Video" (
			"Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			"Vid" character varying(36) NOT NULL,
			"Referer" jsonb NULL,
			"CreateTime" timestamp(3) without time zone NOT NULL,
			"UpDateTime" timestamp(3) without time zone NOT NULL
		)`,
		`CREATE TABLE IF NOT EXISTS "Danmu" (
			"Id" uuid NOT NULL PRIMARY KEY,
			"Vid" character varying(36) NOT NULL,
			"Data" jsonb NOT NULL,
			"Ip" inet NULL,
			"IsDelete" boolean NOT NULL DEFAULT FALSE,
			"VideoId" integer NULL,
			"CreateTime" timestamp(0) without time zone NOT NULL,
			"UpdateTime" timestamp(0) without time zone NOT NULL,
			CONSTRAINT "FK_Danmu_Video_VideoId" FOREIGN KEY ("VideoId") REFERENCES "Video" ("Id") ON DELETE RESTRICT
		)`,
		`CREATE TABLE IF NOT EXISTS "HttpClientCache" (
			"Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			"Key" text NOT NULL,
			"Value" bytea NULL,
			"TimeStamp" bigint NOT NULL
		)`,
		`CREATE INDEX IF NOT EXISTS "IX_Danmu_Vid_IsDelete" ON "Danmu" ("Vid", "IsDelete")`,
		`CREATE INDEX IF NOT EXISTS "IX_Danmu_VideoId" ON "Danmu" ("VideoId")`,
		`CREATE INDEX IF NOT EXISTS "IX_HttpClientCache_Key" ON "HttpClientCache" USING hash ("Key")`,
		`DO $$ BEGIN IF EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='User' AND column_name='UpDateTime') THEN ALTER TABLE "User" RENAME COLUMN "UpDateTime" TO "UpdateTime"; END IF; END $$`,
	}
	for _, statement := range statements {
		if _, err := p.pool.Exec(ctx, statement); err != nil {
			return fmt.Errorf("initialize PostgreSQL schema: %w", err)
		}
	}

	var count int
	if err := p.pool.QueryRow(ctx, `SELECT COUNT(*) FROM "User"`).Scan(&count); err != nil {
		return fmt.Errorf("count users: %w", err)
	}
	if count == 0 {
		salt, err := randomString(6)
		if err != nil {
			return err
		}
		now := time.Now().UTC()
		password := saltedMD5(md5String(p.admin.Password), salt)
		_, err = p.pool.Exec(ctx, `INSERT INTO "User" ("Name", "PassWord", "Salt", "Role", "CreateTime", "UpdateTime") VALUES ($1,$2,$3,1,$4,$4)`, p.admin.User, password, salt, now)
		if err != nil {
			return fmt.Errorf("create initial administrator: %w", err)
		}
	}
	return nil
}

func (p *Postgres) QueryByVid(ctx context.Context, vid string) ([]domain.DanmakuData, error) {
	rows, err := p.pool.Query(ctx, `SELECT "Data" FROM "Danmu" WHERE "Vid"=$1 AND NOT "IsDelete"`, vid)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	result := make([]domain.DanmakuData, 0)
	for rows.Next() {
		var raw []byte
		if err := rows.Scan(&raw); err != nil {
			return nil, err
		}
		data := domain.NewDanmakuData()
		if err := json.Unmarshal(raw, &data); err != nil {
			return nil, fmt.Errorf("decode Danmu.Data: %w", err)
		}
		result = append(result, data)
	}
	return result, rows.Err()
}

func (p *Postgres) Insert(ctx context.Context, vid string, data domain.DanmakuData, ip net.IP, referer domain.Referer) error {
	videoID, err := p.findOrInsertVideo(ctx, vid, referer)
	if err != nil {
		return err
	}
	raw, err := domain.MarshalDBData(data)
	if err != nil {
		return err
	}
	id, err := randomUUID()
	if err != nil {
		return err
	}
	now := time.Now().UTC().Truncate(time.Second)
	var ipValue any
	if ip != nil {
		ipValue = ip.String()
	}
	_, err = p.pool.Exec(ctx, `INSERT INTO "Danmu" ("Id","Vid","Data","Ip","IsDelete","VideoId","CreateTime","UpdateTime") VALUES ($1,$2,$3,$4,FALSE,$5,$6,$6)`, id, vid, raw, ipValue, videoID, now)
	return err
}

func (p *Postgres) findOrInsertVideo(ctx context.Context, vid string, referer domain.Referer) (int, error) {
	rows, err := p.pool.Query(ctx, `SELECT "Id", "Referer" FROM "Video" WHERE "Vid"=$1`, vid)
	if err != nil {
		return 0, err
	}
	defer rows.Close()
	for rows.Next() {
		var id int
		var raw []byte
		if err := rows.Scan(&id, &raw); err != nil {
			return 0, err
		}
		var existing domain.Referer
		if json.Unmarshal(raw, &existing) == nil && existing.Protocol == referer.Protocol && existing.Host == referer.Host && existing.Path == referer.Path && existing.Query == referer.Query {
			return id, nil
		}
	}
	if err := rows.Err(); err != nil {
		return 0, err
	}
	raw, err := domain.MarshalDBReferer(referer)
	if err != nil {
		return 0, err
	}
	now := time.Now().UTC().Truncate(time.Millisecond)
	var id int
	err = p.pool.QueryRow(ctx, `INSERT INTO "Video" ("Vid","Referer","CreateTime","UpDateTime") VALUES ($1,$2,$3,$3) RETURNING "Id"`, vid, raw, now).Scan(&id)
	return id, err
}

func (p *Postgres) List(ctx context.Context, vid string, page, size int, descending bool) (domain.Page[domain.Danmaku], error) {
	page, size = normalizePage(page, size)
	where := ""
	args := []any{}
	if vid != "" {
		where = ` WHERE "Vid"=$1`
		args = append(args, vid)
	}
	var total int
	if err := p.pool.QueryRow(ctx, `SELECT COUNT(*) FROM "Danmu"`+where, args...).Scan(&total); err != nil {
		return domain.Page[domain.Danmaku]{}, err
	}
	direction := "DESC"
	if !descending {
		direction = "ASC"
	}
	args = append(args, size, size*(page-1))
	query := `SELECT "Id"::text,"Vid","Data",COALESCE("Ip"::text,''),"IsDelete","CreateTime","UpdateTime" FROM "Danmu"` + where + ` ORDER BY "CreateTime" ` + direction + fmt.Sprintf(" LIMIT $%d OFFSET $%d", len(args)-1, len(args))
	list, err := p.queryDanmaku(ctx, query, args...)
	return domain.Page[domain.Danmaku]{Total: total, List: list}, err
}

func (p *Postgres) Search(ctx context.Context, filter SearchFilter) (domain.Page[domain.Danmaku], error) {
	filter.Page, filter.Size = normalizePage(filter.Page, filter.Size)
	clauses := []string{"TRUE"}
	args := make([]any, 0, 10)
	add := func(clause string, value any) {
		args = append(args, value)
		clauses = append(clauses, fmt.Sprintf(clause, len(args)))
	}
	if filter.Mode != nil {
		add(`COALESCE(NULLIF(COALESCE("Data"->>'Mode',"Data"->>'mode'),''),'0')::integer=$%d`, *filter.Mode)
	}
	if filter.IP != nil {
		add(`"Ip"=$%d::inet`, filter.IP.String())
	}
	if filter.Start != nil {
		add(`"CreateTime">$%d`, *filter.Start)
	}
	if filter.End != nil {
		add(`"CreateTime"<$%d`, *filter.End)
	}
	if filter.Vid != "" {
		add(`"Vid" LIKE '%%' || $%d || '%%'`, filter.Vid)
	}
	if filter.Author != "" {
		add(`COALESCE("Data"->>'Author',"Data"->>'author','') LIKE '%%' || $%d || '%%'`, filter.Author)
	}
	if filter.AuthorID != nil {
		add(`COALESCE(NULLIF(COALESCE("Data"->>'AuthorId',"Data"->>'authorId'),''),'0')::integer=$%d`, *filter.AuthorID)
	}
	if filter.Key != "" {
		add(`COALESCE("Data"->>'Text',"Data"->>'text','') LIKE '%%' || $%d || '%%'`, filter.Key)
	}
	where := " WHERE " + strings.Join(clauses, " AND ")
	var total int
	if err := p.pool.QueryRow(ctx, `SELECT COUNT(*) FROM "Danmu"`+where, args...).Scan(&total); err != nil {
		return domain.Page[domain.Danmaku]{}, err
	}
	direction := "DESC"
	if !filter.Descending {
		direction = "ASC"
	}
	args = append(args, filter.Size, filter.Size*(filter.Page-1))
	query := `SELECT "Id"::text,"Vid","Data",COALESCE("Ip"::text,''),"IsDelete","CreateTime","UpdateTime" FROM "Danmu"` + where + ` ORDER BY "UpdateTime" ` + direction + fmt.Sprintf(" LIMIT $%d OFFSET $%d", len(args)-1, len(args))
	list, err := p.queryDanmaku(ctx, query, args...)
	return domain.Page[domain.Danmaku]{Total: total, List: list}, err
}

func (p *Postgres) queryDanmaku(ctx context.Context, query string, args ...any) ([]domain.Danmaku, error) {
	rows, err := p.pool.Query(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	list := make([]domain.Danmaku, 0)
	for rows.Next() {
		item, err := scanDanmaku(rows)
		if err != nil {
			return nil, err
		}
		list = append(list, item)
	}
	return list, rows.Err()
}

func scanDanmaku(row pgx.Row) (domain.Danmaku, error) {
	var item domain.Danmaku
	var raw []byte
	var ip string
	if err := row.Scan(&item.ID, &item.Vid, &raw, &ip, &item.IsDeleted, &item.CreateTime, &item.UpdateTime); err != nil {
		return item, err
	}
	item.Data = domain.NewDanmakuData()
	if err := json.Unmarshal(raw, &item.Data); err != nil {
		return item, err
	}
	if ip != "" {
		item.IP = net.ParseIP(strings.Split(ip, "/")[0])
	}
	return item, nil
}

