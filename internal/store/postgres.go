type Postgres struct {
	pool  *pgxpool.Pool
	admin config.AdminSettings
}

const duplicateDanmakuWindow = 30 * time.Second

const duplicateDanmakuQuery = `SELECT EXISTS (
	SELECT 1
	FROM "Danmaku"
	WHERE "Vid"=$1
		AND "Ip" IS NOT DISTINCT FROM $2::inet
		AND md5(COALESCE("Data"->>'Text',''))=md5($3)
		AND COALESCE("Data"->>'Text','')=$3
		AND "CreateTime">=$4
)`

func Open(ctx context.Context, cfg config.Config) (*Postgres, error) {
	poolConfig, err := pgxpool.ParseConfig(cfg.DanmakuSQL.ConnectionString())
	if err != nil {
		return nil, fmt.Errorf("parse PostgreSQL configuration: %w", err)
	}
	poolConfig.MaxConns = cfg.DanmakuSQL.PoolSize
	pool, err := pgxpool.NewWithConfig(ctx, poolConfig)
	if err != nil {
		return nil, fmt.Errorf("open PostgreSQL pool: %w", err)
	}
	if err := pool.Ping(ctx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("connect to PostgreSQL: %w", err)
	}
	return &Postgres{pool: pool, admin: cfg.Admin}, nil
}

func (p *Postgres) Close() { p.pool.Close() }

func (p *Postgres) Initialize(ctx context.Context) error {
	tx, err := p.pool.Begin(ctx)
	if err != nil {
		return fmt.Errorf("begin PostgreSQL schema migration: %w", err)
	}
	defer func() { _ = tx.Rollback(ctx) }()

	for _, statement := range schemaStatements() {
		if _, err := tx.Exec(ctx, statement); err != nil {
			return fmt.Errorf("initialize PostgreSQL schema: %w", err)
		}
	}

	var count int
	if err := tx.QueryRow(ctx, `SELECT COUNT(*) FROM "User"`).Scan(&count); err != nil {
		return fmt.Errorf("count users: %w", err)
	}
	if count == 0 {
		salt, err := randomString(6)
		if err != nil {
			return err
		}
		now := time.Now().UTC()
		password := saltedMD5(md5String(p.admin.Password), salt)
		_, err = tx.Exec(ctx, `INSERT INTO "User" ("Name", "PassWord", "Salt", "Role", "CreateTime", "UpdateTime") VALUES ($1,$2,$3,1,$4,$4)`, p.admin.User, password, salt, now)
		if err != nil {
			return fmt.Errorf("create initial administrator: %w", err)
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return fmt.Errorf("commit PostgreSQL schema migration: %w", err)
	}
	return nil
}

