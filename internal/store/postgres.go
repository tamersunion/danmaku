func (p *Postgres) QueryByVid(ctx context.Context, vid string) ([]domain.DanmakuData, error) {
	rows, err := p.pool.Query(ctx, `SELECT "Data" FROM "Danmaku" WHERE "Vid"=$1 AND NOT "IsDelete"`, vid)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	result := make([]domain.DanmakuData, 0)
	for rows.Next() {
		var raw []byte
		if err := rows.Scan(&raw); err != nil {
			return nil, err
		}
		data := domain.NewDanmakuData()
		if err := json.Unmarshal(raw, &data); err != nil {
			return nil, fmt.Errorf("decode Danmaku.Data: %w", err)
		}
		result = append(result, data)
	}
	return result, rows.Err()
}

func (p *Postgres) Insert(ctx context.Context, vid string, data domain.DanmakuData, ip net.IP, referer domain.Referer) (bool, error) {
	now := time.Now().UTC().Truncate(time.Second)
	var ipValue any
	if ip != nil {
		ipValue = ip.String()
	}
	text := ""
	if data.Text != nil {
		text = *data.Text
	}

	tx, err := p.pool.Begin(ctx)
	if err != nil {
		return false, fmt.Errorf("begin Danmaku insert: %w", err)
	}
	defer func() { _ = tx.Rollback(ctx) }()

	if _, err := tx.Exec(ctx, `SELECT pg_advisory_xact_lock($1)`, duplicateDanmakuAdvisoryKey(vid, ip, text)); err != nil {
		return false, fmt.Errorf("lock duplicate Danmaku submissions: %w", err)
	}
	var duplicate bool
	if err := tx.QueryRow(ctx, duplicateDanmakuQuery, vid, ipValue, text, now.Add(-duplicateDanmakuWindow)).Scan(&duplicate); err != nil {
		return false, fmt.Errorf("check duplicate Danmaku submission: %w", err)
	}
	if duplicate {
		if err := tx.Commit(ctx); err != nil {
			return false, fmt.Errorf("commit duplicate Danmaku check: %w", err)
		}
		return false, nil
	}

	videoID, err := p.findOrInsertVideo(ctx, tx, vid, referer)
	if err != nil {
		return false, err
	}
	raw, err := domain.MarshalDBData(data)
	if err != nil {
		return false, err
	}
	id, err := randomUUID()
	if err != nil {
		return false, err
	}
	if _, err := tx.Exec(ctx, `INSERT INTO "Danmaku" ("Id","Vid","Data","Ip","IsDelete","VideoId","CreateTime","UpdateTime") VALUES ($1,$2,$3,$4,FALSE,$5,$6,$6)`, id, vid, raw, ipValue, videoID, now); err != nil {
		return false, err
	}
	if err := tx.Commit(ctx); err != nil {
		return false, fmt.Errorf("commit Danmaku insert: %w", err)
	}
	return true, nil
}

func duplicateDanmakuAdvisoryKey(vid string, ip net.IP, text string) int64 {
	ipText := ""
	if ip != nil {
		ipText = ip.String()
	}
	hash := sha256.New()
	var size [8]byte
	for _, value := range []string{"danmaku:duplicate:v1", ipText, vid, text} {
		binary.BigEndian.PutUint64(size[:], uint64(len(value)))
		_, _ = hash.Write(size[:])
		_, _ = hash.Write([]byte(value))
	}
	sum := hash.Sum(nil)
	return int64(binary.BigEndian.Uint64(sum[:8]))
}

func (p *Postgres) findOrInsertVideo(ctx context.Context, tx pgx.Tx, vid string, referer domain.Referer) (int, error) {
	rows, err := tx.Query(ctx, `SELECT "Id", "Referer" FROM "Video" WHERE "Vid"=$1`, vid)
	if err != nil {
		return 0, err
	}
	for rows.Next() {
		var id int
		var raw []byte
		if err := rows.Scan(&id, &raw); err != nil {
			return 0, err
		}
		var existing domain.Referer
		if json.Unmarshal(raw, &existing) == nil && existing.Protocol == referer.Protocol && existing.Host == referer.Host && existing.Path == referer.Path && existing.Query == referer.Query {
			rows.Close()
			return id, nil
		}
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return 0, err
	}
	raw, err := domain.MarshalDBReferer(referer)
	if err != nil {
		return 0, err
	}
	now := time.Now().UTC().Truncate(time.Millisecond)
	var id int
	err = tx.QueryRow(ctx, `INSERT INTO "Video" ("Vid","Referer","CreateTime","UpDateTime") VALUES ($1,$2,$3,$3) RETURNING "Id"`, vid, raw, now).Scan(&id)
	return id, err
}

func (p *Postgres) List(ctx context.Context, vid string, page, size int, descending bool) (domain.Page[domain.Danmaku], error) {
	page, size = normalizePage(page, size)
	where := ""
	args := []any{}
	if vid != "" {
		where = ` WHERE "Vid"=$1`
		args = append(args, vid)
	}
	var total int
	if err := p.pool.QueryRow(ctx, `SELECT COUNT(*) FROM "Danmaku"`+where, args...).Scan(&total); err != nil {
		return domain.Page[domain.Danmaku]{}, err
	}
	direction := "DESC"
	if !descending {
		direction = "ASC"
	}
	args = append(args, size, size*(page-1))
	query := `SELECT "Id"::text,"Vid","Data",COALESCE("Ip"::text,''),"IsDelete","CreateTime","UpdateTime" FROM "Danmaku"` + where + ` ORDER BY "CreateTime" ` + direction + fmt.Sprintf(" LIMIT $%d OFFSET $%d", len(args)-1, len(args))
	list, err := p.queryDanmaku(ctx, query, args...)
	return domain.Page[domain.Danmaku]{Total: total, List: list}, err
}

func (p *Postgres) Search(ctx context.Context, filter SearchFilter) (domain.Page[domain.Danmaku], error) {
	filter.Page, filter.Size = normalizePage(filter.Page, filter.Size)
	clauses := []string{"TRUE"}
	args := make([]any, 0, 10)
	add := func(clause string, value any) {
		args = append(args, value)
		clauses = append(clauses, fmt.Sprintf(clause, len(args)))
	}
	if filter.Mode != nil {
		add(`COALESCE(NULLIF(COALESCE("Data"->>'Mode',"Data"->>'mode'),''),'0')::integer=$%d`, *filter.Mode)
	}
	if filter.IP != nil {
		add(`"Ip"=$%d::inet`, filter.IP.String())
	}
	if filter.Start != nil {
		add(`"CreateTime">$%d`, *filter.Start)
	}
	if filter.End != nil {
		add(`"CreateTime"<$%d`, *filter.End)
	}
	if filter.Vid != "" {
		add(`"Vid" LIKE '%%' || $%d || '%%'`, filter.Vid)
	}
	if filter.Author != "" {
		add(`COALESCE("Data"->>'Author',"Data"->>'author','') LIKE '%%' || $%d || '%%'`, filter.Author)
	}
	if filter.AuthorID != nil {
		add(`COALESCE(NULLIF(COALESCE("Data"->>'AuthorId',"Data"->>'authorId'),''),'0')::integer=$%d`, *filter.AuthorID)
	}
	if filter.Key != "" {
		add(`COALESCE("Data"->>'Text',"Data"->>'text','') LIKE '%%' || $%d || '%%'`, filter.Key)
	}
	where := " WHERE " + strings.Join(clauses, " AND ")
	var total int
	if err := p.pool.QueryRow(ctx, `SELECT COUNT(*) FROM "Danmaku"`+where, args...).Scan(&total); err != nil {
		return domain.Page[domain.Danmaku]{}, err
	}
	direction := "DESC"
	if !filter.Descending {
		direction = "ASC"
	}
	args = append(args, filter.Size, filter.Size*(filter.Page-1))
	query := `SELECT "Id"::text,"Vid","Data",COALESCE("Ip"::text,''),"IsDelete","CreateTime","UpdateTime" FROM "Danmaku"` + where + ` ORDER BY "UpdateTime" ` + direction + fmt.Sprintf(" LIMIT $%d OFFSET $%d", len(args)-1, len(args))
	list, err := p.queryDanmaku(ctx, query, args...)
	return domain.Page[domain.Danmaku]{Total: total, List: list}, err
}

func (p *Postgres) queryDanmaku(ctx context.Context, query string, args ...any) ([]domain.Danmaku, error) {
	rows, err := p.pool.Query(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	list := make([]domain.Danmaku, 0)
	for rows.Next() {
		item, err := scanDanmaku(rows)
		if err != nil {
			return nil, err
		}
		list = append(list, item)
	}
	return list, rows.Err()
}

func scanDanmaku(row pgx.Row) (domain.Danmaku, error) {
	var item domain.Danmaku
	var raw []byte
	var ip string
	if err := row.Scan(&item.ID, &item.Vid, &raw, &ip, &item.IsDeleted, &item.CreateTime, &item.UpdateTime); err != nil {
		return item, err
	}
	item.Data = domain.NewDanmakuData()
	if err := json.Unmarshal(raw, &item.Data); err != nil {
		return item, err
	}
	if ip != "" {
		item.IP = net.ParseIP(strings.Split(ip, "/")[0])
	}
	return item, nil
}

